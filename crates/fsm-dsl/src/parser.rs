// Helper to parse type_specifier from its inner rule pair (because type_specifier is silent)
fn parse_type_specifier_from_inner(inner: Pair<Rule>) -> ParseResult<TypeSpecifier> {
     // println!("    Parsing type_specifier from inner: {:?}, text: {:?}", inner.as_rule(), inner.as_str());
     match inner.as_rule() {
        Rule::simple_type => {
            let ident_pair = inner.into_inner().next().ok_or(ParseError::MissingRule { expected: Rule::identifier })?;
            let base_type = parse_identifier(ident_pair)?;
            Ok(TypeSpecifier::Simple(base_type))
        }
        Rule::list_type => {
            // list_type = { "list" ~ "<" ~ type_specifier ~ ">" }
            // inner is list_type. Get the inner type_specifier Pair
            let type_spec_pair = inner.into_inner().next().ok_or(ParseError::MissingRule { expected: Rule::type_specifier })?;
             // Since type_specifier is silent, get its actual inner rule pair (e.g., simple_type)
            let actual_type_pair = type_spec_pair.into_inner().next().ok_or(ParseError::MissingRule { expected: Rule::simple_type /*or others*/ })?;
            let inner_type = parse_type_specifier_from_inner(actual_type_pair)?;
            Ok(TypeSpecifier::List(Box::new(inner_type)))
        }
        Rule::optional_type => {
            // optional_type = { "optional" ~ "<" ~ type_specifier ~ ">" }
            let type_spec_pair = inner.into_inner().next().ok_or(ParseError::MissingRule { expected: Rule::type_specifier })?;
            let actual_type_pair = type_spec_pair.into_inner().next().ok_or(ParseError::MissingRule { expected: Rule::simple_type /*or others*/ })?;
            let inner_type = parse_type_specifier_from_inner(actual_type_pair)?;
            Ok(TypeSpecifier::Optional(Box::new(inner_type)))
        }
        Rule::map_type => {
            // map_type = { "map" ~ "<" ~ type_specifier ~ "," ~ type_specifier ~ ">" }
            let mut inner_pairs = inner.into_inner();
            let key_type_spec_pair = inner_pairs.next().ok_or(ParseError::MissingRule { expected: Rule::type_specifier })?;
            let value_type_spec_pair = inner_pairs.next().ok_or(ParseError::MissingRule { expected: Rule::type_specifier })?;
            // Get actual inner rule pairs for key and value
            let key_actual_type_pair = key_type_spec_pair.into_inner().next().ok_or(ParseError::MissingRule { expected: Rule::simple_type })?;
            let value_actual_type_pair = value_type_spec_pair.into_inner().next().ok_or(ParseError::MissingRule { expected: Rule::simple_type })?;
            let key_type = parse_type_specifier_from_inner(key_actual_type_pair)?;
            let value_type = parse_type_specifier_from_inner(value_actual_type_pair)?;
            Ok(TypeSpecifier::Map(Box::new(key_type), Box::new(value_type)))
        }
        Rule::identifier => { // Handles cases where identifier is passed directly
             Ok(TypeSpecifier::Simple(parse_identifier(inner)?))
        }
        rule => Err(ParseError::UnexpectedRule {
            expected: Rule::simple_type, // Simplified expected rule
            found: rule,
        }),
    }
}

// Basic implementation, needs to handle annotations like $implements, $route
fn parse_service_definition(pair: Pair<Rule>) -> ParseResult<ServiceDefinition> {
     if pair.as_rule() != Rule::service_definition {
        return Err(ParseError::UnexpectedRule { expected: Rule::service_definition, found: pair.as_rule() });
    }
    let mut name: Option<Identifier> = None;
    let mut id: Option<NumericId> = None;
    let mut extends: Option<Identifier> = None;
    let mut annotations = Vec::new();

     for inner_pair in pair.into_inner() {
        match inner_pair.as_rule() {
            Rule::annotation => annotations.push(parse_annotation(inner_pair)?),
            Rule::identifier => name = Some(parse_identifier(inner_pair)?),
            Rule::integer_literal => id = Some(parse_numeric_id(inner_pair)?),
            Rule::service_extends => {
                // service_extends has an inner identifier
                if let Some(extends_pair) = inner_pair.into_inner().next() {
                    if extends_pair.as_rule() == Rule::identifier {
                         extends = Some(parse_identifier(extends_pair)?);
                    } else {
                         return Err(ParseError::UnexpectedRule { expected: Rule::identifier, found: extends_pair.as_rule() });
                    }
                } else {
                     return Err(ParseError::MissingRule { expected: Rule::identifier });
                }
            },
             Rule::service_body => {
                 println!("--- Parsing Service Body ---");
                 // Parse annotations inside the body (e.g., $implements)
                 // inner_pair is service_body. Iterate through service_element pairs within it.
                for service_element_pair in inner_pair.into_inner() {
                     println!("  Found in body: {:?} '{}'", service_element_pair.as_rule(), service_element_pair.as_str());
                     // Grammar: service_element = { annotation }
                     if service_element_pair.as_rule() == Rule::service_element {
                         println!("    Is service_element. Getting inner annotation...");
                         // Get the annotation pair inside service_element
                          if let Some(annotation_pair) = service_element_pair.into_inner().next() {
                               println!("      Got annotation pair: {:?} '{}'", annotation_pair.as_rule(), annotation_pair.as_str());
                               // Call parse_annotation directly, let it determine the specific type
                               match parse_annotation(annotation_pair.clone()) { // Clone for potential reuse
                                   Ok(anno) => {
                                       println!("      Successfully parsed annotation: {:?}", anno);
                                       annotations.push(anno);
                                   }
                                   Err(e) => {
                                       println!("      Error parsing annotation: {}", e);
                                       return Err(e); // Propagate error
                                   }
                               }
                          } else {
                               println!("    Error: service_element was empty");
                               return Err(ParseError::MissingRule { expected: Rule::annotation });
                          }
                     } else {
                          println!("    Error: Expected service_element, found {:?}", service_element_pair.as_rule());
                          return Err(ParseError::UnexpectedRule { expected: Rule::service_element, found: service_element_pair.as_rule() });
                     }
                 }
                 println!("--- Finished Service Body ---");
             },
            _ => return Err(ParseError::UnexpectedRule { expected: Rule::identifier, found: inner_pair.as_rule() })
        }
    }

     Ok(ServiceDefinition {
        name: name.ok_or(ParseError::MissingRule { expected: Rule::identifier })?,
        id: id.ok_or(ParseError::MissingRule { expected: Rule::integer_literal })?,
        extends,
        annotations, // Contains $implements, $route etc.
    })
}

